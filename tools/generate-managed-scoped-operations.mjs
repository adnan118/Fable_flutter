#!/usr/bin/env node
/**
 * RC106 — Generate ONLY explicitly-selected Fable managed-entity operation
 * constants. This is not a repository, DTO or permission generator.
 * Refuses fixtures, stale hashes, unpinned projects and Other Backend.
 */
import {existsSync,readFileSync,mkdirSync,writeFileSync,lstatSync} from 'node:fs';
import {resolve,join,dirname} from 'node:path';
import {pathToFileURL} from 'node:url';
import {verifyFableContract} from './verify-fable-contract.mjs';

export const OUTPUT='lib/src/generated/managed_scoped_operations.dart';
const REQUIREMENTS='.fable/feature-integration-requirements.json';
const PROJECT_SETUP='.fable/frontend-setup.json';
const SOURCE='assets/contracts/contract.json';
const SAFE_ID=/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,190}$/;
const validId=value=>typeof value==='string'&&SAFE_ID.test(value);
const HASH=/^[a-f0-9]{64}$/;
const METHODS=new Set(['GET','POST','PUT','PATCH','DELETE']);

function readJson(path){return JSON.parse(readFileSync(path,'utf8'));}
function forbiddenPath(path){
  return typeof path!=='string'||!path.startsWith('/')||path.startsWith('//')||
    path.includes('..')||path.includes('\\')||path.includes('?')||
    path.includes('#')||path.includes('%')||path.includes('$')||
    path==='/auth'||path.startsWith('/auth/')||
    path==='/permissions'||path.startsWith('/permissions/')||
    path==='/admin'||path.startsWith('/admin/')||
    path==='/managed-entities/public'||path.startsWith('/managed-entities/public/');
}
function safeDartString(text){
  if(typeof text!=='string'||/[\x00-\x1f\x7f$\\]/.test(text))
    throw Error('Untrusted Dart string in selected scope');
  return JSON.stringify(text);
}

export function planManagedScopedOperations(contract,requirements,selectedFeatures){
  if(contract?.kind!=='fable.client-contract'||!HASH.test(contract.contractHash)||
     !Array.isArray(contract.operations))
    throw Error('Verified Fable project contract operations required');
  if(requirements?.kind!=='fable.feature-integration-requirements'||
     requirements.schemaVersion!==1||
     !requirements.features||typeof requirements.features!=='object'||
     Array.isArray(requirements.features))
    throw Error('Project operation requirements not declared');
  if(!Array.isArray(selectedFeatures)||
     selectedFeatures.some(id=>!validId(id)))
    throw Error('Explicit project feature selection required');
  const selected=new Set(selectedFeatures),mapped=new Map();
  for(const [feature,spec] of Object.entries(requirements.features)){
    if(!validId(feature)||!selected.has(feature))
      throw Error('Scoped feature not explicitly selected: '+feature);
    if(!Array.isArray(spec?.operations))
      throw Error('Required operation list missing: '+feature);
    for(const requested of spec.operations){
      if(requested?.managedEntityScope===undefined ||
         requested.managedEntityScope===false)continue;
      if(requested.managedEntityScope!==true)
        throw Error('Managed scope flag must be boolean: '+feature);
      const {operationId,method,path}=requested;
      if(!validId(operationId)||!METHODS.has(method)||
         forbiddenPath(path))
        throw Error('Unsafe or incomplete managed scope operation: '+feature);
      const imported=contract.operations.filter(op=>op.operationId===operationId);
      if(imported.length!==1||imported[0].method!==method||
         imported[0].path!==path||imported[0].public!==false)
        throw Error('Managed scoped operation not pinned to authenticated Fable contract: '+operationId);
      if(mapped.has(operationId))
        throw Error('Same scoped operation selected multiple times: '+operationId);
      mapped.set(operationId,{feature,operationId,method,path});
    }
  }
  return [...mapped.values()].sort((a,b)=>a.operationId.localeCompare(b.operationId));
}

export function renderManagedScopedDart(operations,contractHash){
  if(!HASH.test(contractHash))throw Error('Invalid project contract hash');
  const lines=[
    '// GENERATED BY FABLE WIZARD RC106 from a project-pinned Backend contract.',
    '// Source-mapped only. Backend authorizes every request; not live E2E.',
    '// Do not put tokens, permission grants, or arbitrary request headers here.',
    "import 'package:fable_profile/fable_profile.dart';",
    '',
    'const Map<String,FableManagedScopedOperation> projectManagedScopedOperations =',
    '  <String,FableManagedScopedOperation>{',
  ];
  for(const op of operations){
    // String validation also blocks Dart interpolation and code injection.
    for(const v of [op.feature,op.operationId,op.method,op.path])safeDartString(v);
    lines.push('    '+safeDartString(op.feature+'.'+op.operationId)+
      ': FableManagedScopedOperation(',
      '      operationId: '+safeDartString(op.operationId)+',',
      '      method: '+safeDartString(op.method)+',',
      '      path: '+safeDartString(op.path)+',',
      '      contractHash: '+safeDartString(contractHash)+',',
      '    ),');
  }
  lines.push('  };','');
  return lines.join('\n');
}

// This helper is intentionally separate so overwrite safety is directly
// testable without manufacturing or trusting a fake production Backend.
export function writeManagedScopedOutput(output,content){
  if(typeof output!=='string'||!output||typeof content!=='string'||
     !content.startsWith('// GENERATED BY FABLE WIZARD RC106 ')){
    throw Error('Only reviewed Fable-generated output can be written');
  }
  if(existsSync(output)){
    if(lstatSync(output).isSymbolicLink())
      throw Error('Refusing to follow a symlink for generated output');
    if(readFileSync(output,'utf8')!==content)
      throw Error('Existing scoped bindings differ: review diff and move aside before --apply');
    return false; // Idempotent, byte-identical output.
  }
  mkdirSync(dirname(output),{recursive:true});
  writeFileSync(output,content,{encoding:'utf8',flag:'wx'});
  return true;
}

export function collectManagedSelectedFeatures(root){
  root=resolve(root);
  const selectionPath=join(root,'.fable','mobile-features.json');
  const customPath=join(root,'.fable','project-features.json');
  const selected=new Set();
  if(existsSync(selectionPath)){
    const manifest=readJson(selectionPath);
    if(!Array.isArray(manifest.features))
      throw Error('Invalid mobile feature selection manifest');
    for(const id of manifest.features)selected.add(id);
  }
  if(existsSync(customPath)){
    const manifest=readJson(customPath);
    if(!Array.isArray(manifest.features))
      throw Error('Invalid selected project features');
    for(const feature of manifest.features){
      selected.add(typeof feature==='string'?feature:feature?.id);
    }
  }
  // Frontend-owned decisions may disable a package even if it still appears
  // in a previously imported source inventory. Never regenerate its scope.
  const localChoices=join(root,'.fable','frontend-owned-decisions.json');
  if(existsSync(localChoices)){
    const owned=readJson(localChoices);
    if(owned.kind!=='fable.flutter-owned-decisions' ||
       !owned.choices || typeof owned.choices!=='object')
      throw Error('Malformed local feature decisions');
    for(const [name,choice] of Object.entries(owned.choices)){
      if(choice?.enabled===false){
        // A feature may be listed in BOTH project and mobile inventories.
        // A local disable decision revokes every occurrence, not just one.
        selected.delete(name);
      }else if(choice?.enabled===true&&!selected.has(name)){
        selected.add(name);
      }
    }
  }
  return [...selected];
}

export function generatePinnedManagedScopedOperations(root,{
  expectedProjectId,expectedContractHash,apply=false,
}={}){
  root=resolve(root);
  if(typeof expectedProjectId!=='string'||!expectedProjectId||
     !HASH.test(expectedContractHash))
    throw Error('Independent project ID and SHA-256 contract pin required');
  const setupPath=join(root,PROJECT_SETUP),requirementsPath=join(root,REQUIREMENTS);
  if(!existsSync(setupPath)||!existsSync(requirementsPath))
    throw Error('Approved frontend setup and explicit scoped operation requirements required');
  const setup=readJson(setupPath);
  if(setup.kind!=='fable.flutter-frontend-setup'||
     setup.source!=='backend-contract-export'||setup.mode!=='import'||
     setup.backendAuthority!==true||setup.projectBound!==true||
     setup.projectId!==expectedProjectId||
     setup.contractHash!==expectedContractHash)
    throw Error('Frontend project not independently pinned to active Fable Backend');
  const verification=verifyFableContract(root,{
    mode:'project',expectedProjectId,expectedContractHash,
  });
  if(!verification.ok||!verification.projectBound||verification.fixture)
    throw Error('Cannot generate bindings from unverified or fixture Fable Backend');
  const contract=readJson(join(root,SOURCE));
  const required=readJson(requirementsPath);
  const operations=planManagedScopedOperations(contract,required,
    collectManagedSelectedFeatures(root));
  const output=join(root,OUTPUT);
  if(apply){
    // Never overwrite a manually edited/stale generated file silently.
    // Require a reviewed diff and deliberate removal before regeneration.
    writeManagedScopedOutput(output,
      renderManagedScopedDart(operations,expectedContractHash));
  }
  return {projectId:expectedProjectId,contractHash:expectedContractHash,
    output:OUTPUT,count:operations.length,applied:Boolean(apply),
    liveE2EVerified:false,operations:operations.map(x=>x.operationId)};
}
function cli(argv){
  const options={root:process.cwd(),apply:false};
  for(let i=0;i<argv.length;i++){
    const flag=argv[i];
    if(flag==='--apply')options.apply=true;
    else if(flag==='--root'&&argv[i+1])options.root=argv[++i];
    else if(flag==='--expected-project-id'&&argv[i+1])options.expectedProjectId=argv[++i];
    else if(flag==='--expected-contract-hash'&&argv[i+1])options.expectedContractHash=argv[++i];
    else throw Error('Unknown or missing flag: '+flag);
  }
  return generatePinnedManagedScopedOperations(options.root,options);
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  try{process.stdout.write(JSON.stringify(cli(process.argv.slice(2)),null,2)+'\n');}
  catch(error){process.stderr.write(String(error.message)+'\n');process.exitCode=2;}
}
