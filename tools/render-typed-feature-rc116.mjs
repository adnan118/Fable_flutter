function exactInstantDtoValidator(){
  return [
    'bool _validFableInstant(Object? input){',
    '  if(input is! String || input.length>40 ||',
    '     !RegExp(r"^[0-9]{4}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12][0-9]|3[01])T(?:[01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9](?:[.][0-9]{1,9})?(?:Z|[+-](?:(?:0[0-9]|1[0-3]):[0-5][0-9]|14:00))$").hasMatch(input))',
    '    return false;',
    '  if(DateTime.tryParse(input)==null)return false;',
    '  final y=int.parse(input.substring(0,4));',
    '  final m=int.parse(input.substring(5,7));',
    '  final d=int.parse(input.substring(8,10));',
    '  final day=DateTime.utc(y,m,d);',
    '  return day.year==y && day.month==m && day.day==d;',
    '}',
  ];
}

function listDto(op){
  const name=op.className,item=name+'Item';
  const parts=[
    '// GENERATED RC271: strict list JSON boundary; no dynamic UI data.',
    "import '../domain/"+snake(op.operationId)+"_entity.dart';",
    ...(op.fields.some(f=>f.datetime)?exactInstantDtoValidator():[]),
    'final class '+name+'Dto {',
    '  const '+name+'Dto(this._value);',
    '  final '+name+'Entity _value;',
    '  factory '+name+'Dto.fromJson(Map<String,Object?> raw){',
    "    final input=raw['items'],meta=raw['meta'];",
    '    if(input is! List || input.length>'+
      (op.resultKind==='paginated-list'?'20':'5000')+' || meta is! Map ||',
    ...(op.resultKind==='paginated-list'?[
      "       "+(op.supportsSearch
        ?"(meta['mode']!='page' && meta['mode']!='search')"
        :"meta['mode']!='page'")+" ||",
      ...(op.supportsSearch?[
        "       (meta['mode']=='search' &&",
        "         (meta['count'] is! int || meta['count']!=input.length)) ||",
      ]:[]),
      "       meta['page'] is! int || meta['limit'] is! int ||",
      "       meta['total'] is! int || meta['totalPages'] is! int ||",
      "       (meta['page'] as int)<1 || (meta['page'] as int)>100000 ||",
      "       (meta['limit'] as int)!=20 ||",
      "       (meta['total'] as int)<0 ||",
      "       (meta['totalPages'] as int)<0 ||",
      "       (meta['total'] as int)==0 && (meta['totalPages'] as int)!=0 ||",
      "       (meta['total'] as int)>0 &&",
      "       (meta['totalPages'] as int)!=(((meta['total'] as int)+19)~/20) ||",
      "       (meta['totalPages'] as int)>0 &&",
      "       (meta['page'] as int)>(meta['totalPages'] as int) ||",
      "       input.length>20)",
      "      throw const FormatException('Invalid signed page-mode list envelope');",
    ]:[
      "       meta['mode']!='unpaginated' ||",
      "       meta['count'] is! int || meta['maxRows'] is! int ||",
      "       meta['limitExceeded'] is! bool ||",
      "       (meta['count'] as int)!=input.length ||",
      "       (meta['maxRows'] as int)<1 || (meta['maxRows'] as int)>5000 ||",
      "       input.length>(meta['maxRows'] as int) ||",
      "       (meta['limitExceeded']==true &&",
      "         input.length!=(meta['maxRows'] as int)))",
      "      throw const FormatException('Invalid signed unpaginated list envelope');",
    ]),
    '    final items=<'+item+'>[];',
    '    for(final record in input){',
    '      if(record is! Map || record.keys.any((k)=>k is! String))',
    "        throw const FormatException('Invalid list item object');",
    '      final row=Map<String,Object?>.from(record);',
  ];
  for(const f of op.fields){
    const property="row["+dart(f.name)+"]";
    const check=f.required?f.name+' is! '+(f.type==='double'?'num':f.type):
      '('+f.name+'!=null && '+f.name+' is! '+(f.type==='double'?'num':f.type)+')';
    parts.push('      final '+f.name+'='+property+';',
      '      if('+check+')',
      '        throw const FormatException('+dart('Invalid '+f.name+' list field')+');');
    if(f.decimal)parts.push(
      '      if('+f.name+'!=null && !RegExp(r"^-?(?:0|[1-9][0-9]{0,34})(?:\\.[0-9]{1,30})?(?:e[+-]?[0-9]{1,2})?$").hasMatch('+f.name+' as String))',
      '        throw const FormatException('+dart('Invalid '+f.name+' exact Decimal field')+');',
    );
    if(f.uuid)parts.push(
      '      if('+f.name+'!=null && !RegExp(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-4[0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$").hasMatch('+f.name+' as String))',
      '        throw const FormatException('+dart('Invalid '+f.name+' UUID field')+');',
    );
    if(f.datetime)parts.push(
      '      if('+f.name+'!=null && !_validFableInstant('+f.name+'))',
      '        throw const FormatException('+dart('Invalid '+f.name+' datetime field')+');',
    );
  }
  parts.push('      items.add('+item+'(');
  for(const f of op.fields){
    const value=f.type==='double'?(f.required?f.name+'.toDouble()':'('+f.name+' as num?)?.toDouble()'):
      (f.required?f.name:f.name+' as '+fieldType(f));
    parts.push('        '+f.name+': '+value+',');
  }
  parts.push(
    '      ));',
    '    }',
    '    return '+name+'Dto('+name+'Entity(',
    '      items:List<'+item+'>.unmodifiable(items),',
    ...(op.resultKind==='paginated-list'?[
      '      mode:meta["mode"]=="search"?'+name+'ListMode.search:'+name+'ListMode.page,',
      "      page:meta['page'] as int,",
      "      limit:meta['limit'] as int,",
      "      total:meta['total'] as int,",
      "      totalPages:meta['totalPages'] as int,",
    ]:[
      "      count:meta['count'] as int,",
      "      maxRows:meta['maxRows'] as int,",
      "      limitExceeded:meta['limitExceeded'] as bool,",
    ]),
    '    ));',
    '  }',
    '  '+name+'Entity toDomain()=>_value;',
    '}',
  );
  return line(...parts);
}

function dto(op){
  if(['unpaginated-list','paginated-list'].includes(op.resultKind))return listDto(op);
  const name=op.className,parts=[
    '// GENERATED by Fable RC116: typed Data DTO, strict source-field parsing.',
    "import '../domain/"+snake(op.operationId)+"_entity.dart';",
    ...(op.fields.some(f=>f.datetime)?exactInstantDtoValidator():[]),
    'final class '+name+'Dto {',
    '  const '+name+'Dto({'+op.fields.map(f=>(f.required?'required this.':'this.')+f.name).join(', ')+'});',
    ...op.fields.map(f=>'  final '+fieldType(f)+' '+f.name+';'),
    '  factory '+name+'Dto.fromJson(Map<String,Object?> raw){',
  ];
  for(const f of op.fields){
    const property="raw["+dart(f.name)+"]";
    parts.push('    final '+f.name+' = '+property+';');
    const guard=f.required?f.name+' is! '+(f.type==='double'?'num':f.type):
      '('+f.name+'!=null && '+f.name+' is! '+(f.type==='double'?'num':f.type)+')';
    parts.push('    if('+guard+') throw const FormatException('+dart('Invalid '+f.name+' DTO field')+');');
    if(f.decimal)parts.push(
      '    if('+f.name+'!=null && !RegExp(r"^-?(?:0|[1-9][0-9]{0,34})(?:\\.[0-9]{1,30})?(?:e[+-]?[0-9]{1,2})?$").hasMatch('+f.name+' as String))',
      '      throw const FormatException('+dart('Invalid '+f.name+' exact Decimal field')+');',
    );
    if(f.uuid)parts.push(
      '    if('+f.name+'!=null && !RegExp(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-4[0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$").hasMatch('+f.name+' as String))',
      '      throw const FormatException('+dart('Invalid '+f.name+' UUID field')+');',
    );
    if(f.datetime)parts.push(
      '    if('+f.name+'!=null && !_validFableInstant('+f.name+'))',
      '      throw const FormatException('+dart('Invalid '+f.name+' datetime field')+');',
    );
  }
  parts.push('    return '+name+'Dto(');
  for(const f of op.fields){
    // Required locals are promoted by the throwing guard. For optional
    // values a conjunction guard retains Object?, so keep only those casts.
    const conv=f.type==='double'?(f.required?f.name+'.toDouble()':'('+f.name+' as num?)?.toDouble()'):
      (f.required?f.name:f.name+' as '+fieldType(f));
    parts.push('      '+f.name+': '+conv+',');
  }
  parts.push('    );','  }',
    '  '+name+'Entity toDomain()=>'+name+'Entity(',
    ...op.fields.map(f=>'    '+f.name+': '+f.name+','),
    '  );','}');
  return line(...parts);
}
