function dto(op){
  if(['unpaginated-list','paginated-list'].includes(op.resultKind))return listDto(op);
  const name=op.className,parts=[
    '// GENERATED by Fable RC116: typed Data DTO, strict source-field parsing.',
    "import '../domain/"+snake(op.operationId)+"_entity.dart';",
    'final class '+name+'Dto {',
    '  const '+name+'Dto({'+op.fields.map(f=>(f.required?'required this.':'this.')+f.name).join(', ')+'});',
    ...op.fields.map(f=>'  final '+fieldType(f)+' '+f.name+';'),
    '  factory '+name+'Dto.fromJson(Map<String,Object?> raw){',
  ];
  for(const f of op.fields){
    const property="raw["+dart(f.name)+"]";
    parts.push('    final '+f.name+' = '+property+';');
    const guard=f.required?f.name+' is! '+(f.type==='double'?'num':f.type):
      '('+f.name+'!=null && '+f.name+' is! '+(f.type==='double'?'num':f.type)+')';
    parts.push('    if('+guard+') throw const FormatException('+dart('Invalid '+f.name+' DTO field')+');');
  }
  parts.push('    return '+name+'Dto(');
  for(const f of op.fields){
    // Required locals are promoted by the throwing guard. For optional
    // values a conjunction guard retains Object?, so keep only those casts.
    const conv=f.type==='double'?(f.required?f.name+'.toDouble()':'('+f.name+' as num?)?.toDouble()'):
      (f.required?f.name:f.name+' as '+fieldType(f));
    parts.push('      '+f.name+': '+conv+',');
  }
  parts.push('    );','  }',
    '  '+name+'Entity toDomain()=>'+name+'Entity(',
    ...op.fields.map(f=>'    '+f.name+': '+f.name+','),
    '  );','}');
  return line(...parts);
}
