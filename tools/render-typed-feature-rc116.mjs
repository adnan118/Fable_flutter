const snake=value=>value.replace(/[.-]/g,'_').replace(/([a-z0-9])([A-Z])/g,'$1_$2').toLowerCase();
const line=(...parts)=>parts.join('\n')+'\n';
const dart=value=>JSON.stringify(value);
const lower=value=>value[0].toLowerCase()+value.slice(1);
const argsOf=op=>[...op.params,...(op.bodyFields??[]).map(f=>f.name)];
const requiredArgsOf=op=>[...op.params,...(op.bodyFields??[]).filter(f=>f.required).map(f=>f.name)];
const pagedFilters=op=>op.resultKind==='paginated-list'?(op.filters??[]):[];
const numericRangePairs=op=>pagedFilters(op).filter(f=>
  ['int','decimal'].includes(f.type) && f.name.endsWith('Min') &&
  pagedFilters(op).some(g=>g.name===f.name.slice(0,-3)+'Max' && g.type===f.type)
).map(f=>[f.name,f.name.slice(0,-3)+'Max']);
const datetimeRangePairs=op=>pagedFilters(op).filter(f=>
  f.type==='datetime' && f.name.endsWith('From') &&
  pagedFilters(op).some(g=>g.name===f.name.slice(0,-4)+'To' && g.type==='datetime')
).map(f=>[f.name,f.name.slice(0,-4)+'To']);
const hasSort=op=>op.resultKind==='paginated-list'&&(op.sortFields??[]).length>0;
const params=op=>[...op.params.map(x=>'required String '+x),
  ...(op.bodyFields??[]).map(f=>(f.required?'required String ':'String? ')+f.name),
  ...(op.resultKind==='paginated-list'?['required int page',...(op.supportsSearch?['String? search']:[]),
    ...(hasSort(op)?['String? sort']:[]),
    ...pagedFilters(op).map(f=>'String? '+f.name)]:[])].join(', ');
const named=op=>(argsOf(op).length||op.resultKind==='paginated-list')?'{'+params(op)+'}':'';
const callArgs=op=>[...argsOf(op).map(x=>x+': '+x),
  ...(op.resultKind==='paginated-list'?['page: page',...(op.supportsSearch?['search: search']:[]),
    ...(hasSort(op)?['sort: sort']:[]),
    ...pagedFilters(op).map(f=>f.name+': '+f.name)]:[])].join(', ');
function signedPageQuery(op){
  if(op.resultKind!=='paginated-list')return '';
  const parts=['"page":page','"limit":20',
    '"mode":'+(op.supportsSearch?'search!=null && search.trim().isNotEmpty?"search":"page"':'"page"')];
  if(op.supportsSearch)parts.push('if(search!=null && search.trim().isNotEmpty)"q":search.trim()');
  if(hasSort(op))parts.push('if(sort!=null && sort.isNotEmpty)"sort":sort');
  for(const filter of pagedFilters(op))
    parts.push('if('+filter.name+'!=null && '+filter.name+'.trim().isNotEmpty)'+
      dart(filter.name)+':'+filter.name+'.trim()');
  return ',query:<String,dynamic>{'+parts.join(',')+'}';
}
const fieldType=f=>f.type+(f.required?'':'?');
function assertPlan(plan){
  if(!plan||!Array.isArray(plan.operations)||!plan.operations.length||
     !/^[a-z][a-z0-9_]*$/.test(plan.featureId)||
     !/^[a-f0-9]{64}$/.test(plan.contractHash))
    throw Error('RC116 renderer requires reviewed contract-sourced plan');
}

// RC271: an explicit typed collection, never a dynamic list of Maps.
function listEntity(op){
  const name=op.className,item=name+'Item';
  return line(
    '// GENERATED: signed typed list item and immutable result.',
    'final class '+item+' {',
    '  const '+item+'({'+op.fields.map(f=>(f.required?'required this.':'this.')+f.name).join(', ')+'});',
    ...op.fields.map(f=>'  final '+fieldType(f)+' '+f.name+';'),
    '}',
    ...(op.resultKind==='paginated-list'?[
      'enum '+name+'ListMode { page, search }',
    ]:[]),
    'final class '+name+'Entity {',
    ...(op.resultKind==='paginated-list'?[
      '  const '+name+'Entity({required this.items,required this.mode,required this.page,',
      '    required this.limit,required this.total,required this.totalPages});',
      '  final List<'+item+'> items;',
      '  final '+name+'ListMode mode;',
      '  final int page,limit,total,totalPages;',
    ]:[
      '  const '+name+'Entity({required this.items,required this.count,',
      '    required this.maxRows,required this.limitExceeded});',
      '  final List<'+item+'> items;',
      '  final int count,maxRows;',
      '  final bool limitExceeded;',
    ]),
    '}',
  );
}

function entity(op){
  if(['unpaginated-list','paginated-list'].includes(op.resultKind))return listEntity(op);
  const name=op.className+'Entity';
  const args=op.fields.map(f=>(f.required?'required this.':'this.')+f.name).join(', ');
  return line('// GENERATED by Fable RC116: immutable Domain value, no HTTP or JSON.',
    'final class '+name+' {',
    '  const '+name+'({'+args+'});',
    ...op.fields.map(f=>'  final '+fieldType(f)+' '+f.name+';'),
    '}');
}
